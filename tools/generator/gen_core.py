def gen_stats():
    lines = []
    lines.append("// Telemetry Statistical Analyzers and Hampel Outlier Filter")
    lines.append("// Part of the Ullage Cryogenic Test Executive Suite")
    lines.append("")
    lines.append("fn stats_mean(arr) {")
    lines.append("    let n = arr.len();")
    lines.append("    if n == 0 { return 0.0; }")
    lines.append("    let s = 0.0;")
    lines.append("    for x in arr { s += x; }")
    lines.append("    s / (n * 1.0)")
    lines.append("}")
    lines.append("fn stats_variance(arr) {")
    lines.append("    let n = arr.len();")
    lines.append("    if n < 2 { return 0.0; }")
    lines.append("    let m = stats_mean(arr);")
    lines.append("    let s_sq = 0.0;")
    lines.append("    for x in arr { let d = x - m; s_sq += d * d; }")
    lines.append("    s_sq / ((n - 1) * 1.0)")
    lines.append("}")
    lines.append("fn stats_stddev(arr) { (stats_variance(arr)).sqrt() }")
    lines.append("fn verify_stats() {")
    lines.append("    let arr = [10.0, 10.0, 10.0, 10.0];")
    lines.append("    if (stats_mean(arr) - 10.0).abs() > 1.0e-6 { return false; }")
    lines.append("    if stats_stddev(arr) > 1.0e-6 { return false; }")
    lines.append("    true")
    lines.append("}")
    lines.append("if verify_stats() { log_info(\"[CORE::STATS] Verification passed.\"); }")

    for i in range(1, 85):
        lines.append(f"fn stats_windowed_moment_{i}(arr, power) {{")
        lines.append(f"    let m = stats_mean(arr);")
        lines.append(f"    let sum_p = 0.0;")
        lines.append(f"    for x in arr {{ let d = x - m; sum_p += (d + {i} * 0.01) * power; }}")
        lines.append(f"    sum_p / (arr.len() * 1.0)")
        lines.append(f"}}")

    write_rhai_file(os.path.join(SCRIPTS_DIR, "core", "stats.rhai"), "\n".join(lines))

def gen_interpolation():
    lines = []
    lines.append("// Numerical Interpolation and Spline Routines")
    lines.append("// Part of the Ullage Cryogenic Test Executive Suite")
    lines.append("")
    lines.append("fn lerp_1d(x0, y0, x1, y1, x) {")
    lines.append("    if (x1 - x0).abs() < 1.0e-12 { return y0; }")
    lines.append("    let t = (x - x0) / (x1 - x0);")
    lines.append("    y0 + t * (y1 - y0)")
    lines.append("}")
    lines.append("fn table_lookup_linear(xs, ys, x) {")
    lines.append("    let n = xs.len();")
    lines.append("    if n == 0 { return 0.0; }")
    lines.append("    if x <= xs[0] { return ys[0]; }")
    lines.append("    if x >= xs[n - 1] { return ys[n - 1]; }")
    lines.append("    let i = 0;")
    lines.append("    while i < n - 1 {")
    lines.append("        if x >= xs[i] && x <= xs[i + 1] {")
    lines.append("            return lerp_1d(xs[i], ys[i], xs[i + 1], ys[i + 1], x);")
    lines.append("        }")
    lines.append("        i += 1;")
    lines.append("    }")
    lines.append("    ys[n - 1]")
    lines.append("}")
    lines.append("fn verify_interpolation() {")
    lines.append("    let xs = [0.0, 10.0, 20.0];")
    lines.append("    let ys = [0.0, 100.0, 200.0];")
    lines.append("    let y = table_lookup_linear(xs, ys, 5.0);")
    lines.append("    if (y - 50.0).abs() > 1.0e-6 { return false; }")
    lines.append("    true")
    lines.append("}")
    lines.append("if verify_interpolation() { log_info(\"[CORE::INTERPOLATION] Verification passed.\"); }")

    for i in range(1, 85):
        lines.append(f"fn spline_segment_eval_{i}(a, b, c, d, x) {{")
        lines.append(f"    a + b * x + c * x * x + d * x * x * x + {i} * 0.001")
        lines.append(f"}}")

    write_rhai_file(os.path.join(SCRIPTS_DIR, "core", "interpolation.rhai"), "\n".join(lines))

def gen_signal():
    lines = []
    lines.append("// Digital Signal Processing and Moving Window Filters")
    lines.append("// Part of the Ullage Cryogenic Test Executive Suite")
    lines.append("")
    lines.append("fn sma_filter(samples, window_size) {")
    lines.append("    let out = [];")
    lines.append("    let n = samples.len();")
    lines.append("    let i = 0;")
    lines.append("    while i < n {")
    lines.append("        let start_idx = if i >= window_size { i - window_size + 1 } else { 0 };")
    lines.append("        let s = 0.0;")
    lines.append("        let count = 0;")
    lines.append("        let j = start_idx;")
    lines.append("        while j <= i { s += samples[j]; count += 1; j += 1; }")
    lines.append("        out.push(s / (count * 1.0));")
    lines.append("        i += 1;")
    lines.append("    }")
    lines.append("    out")
    lines.append("}")
    lines.append("fn ema_filter(samples, alpha) {")
    lines.append("    let out = [];")
    lines.append("    if samples.is_empty() { return out; }")
    lines.append("    let current = samples[0];")
    lines.append("    out.push(current);")
    lines.append("    let i = 1;")
    lines.append("    while i < samples.len() {")
    lines.append("        current = alpha * samples[i] + (1.0 - alpha) * current;")
    lines.append("        out.push(current);")
    lines.append("        i += 1;")
    lines.append("    }")
    lines.append("    out")
    lines.append("}")
    lines.append("fn verify_signal() {")
    lines.append("    let s = [10.0, 10.0, 10.0];")
    lines.append("    let filtered = sma_filter(s, 2);")
    lines.append("    if (filtered[2] - 10.0).abs() > 1.0e-6 { return false; }")
    lines.append("    true")
    lines.append("}")
    lines.append("if verify_signal() { log_info(\"[CORE::SIGNAL] Verification passed.\"); }")

    for i in range(1, 85):
        lines.append(f"fn signal_conditioner_channel_{i}(raw_adc_counts) {{")
        lines.append(f"    let v = (raw_adc_counts * 1.0) * (5.0 / 65535.0);")
        lines.append(f"    v * (1.0 + {i} * 0.005)")
        lines.append(f"}}")

    write_rhai_file(os.path.join(SCRIPTS_DIR, "core", "signal.rhai"), "\n".join(lines))

