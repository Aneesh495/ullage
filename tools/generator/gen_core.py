def gen_vector():
    lines = []
    lines.append("// 3D and 4D Vector Algebra and Kinematics")
    lines.append("// Part of the Ullage Cryogenic Test Executive Suite")
    lines.append("")
    lines.append("fn vec3_new(x, y, z) { #{ \"x\": x, \"y\": y, \"z\": z } }")
    lines.append("fn vec3_zero() { vec3_new(0.0, 0.0, 0.0) }")
    lines.append("fn vec3_add(a, b) { vec3_new(a.x + b.x, a.y + b.y, a.z + b.z) }")
    lines.append("fn vec3_sub(a, b) { vec3_new(a.x - b.x, a.y - b.y, a.z - b.z) }")
