    lines.append("fn vec3_dot(a, b) { a.x * b.x + a.y * b.y + a.z * b.z }")
    lines.append("fn vec3_cross(a, b) {")
    lines.append("    vec3_new(")
    lines.append("        a.y * b.z - a.z * b.y,")
    lines.append("        a.z * b.x - a.x * b.z,")
    lines.append("        a.x * b.y - a.y * b.x")
    lines.append("    )")
    lines.append("}")
    lines.append("fn vec3_norm_sq(v) { vec3_dot(v, v) }")
