def gen_pressure_drop():
    lines = []
    lines.append("// Pipe Hydraulic Friction and Darcy-Weisbach Head Loss")
    lines.append("// Colebrook-White friction factor via Haaland explicit approximation")
    lines.append("")
    lines.append("fn friction_factor_haaland(reynolds, roughness_m, diameter_m) {")
    lines.append("    if reynolds < 2300.0 { return 64.0 / reynolds; }")
    lines.append("    let eps_d = roughness_m / diameter_m;")
    lines.append("    let term = ((eps_d / 3.7).powf(1.11)) + (6.9 / reynolds);")
    lines.append("    let log_term = term.log10();")
    lines.append("    let inv_sqrt_f = -1.8 * log_term;")
    lines.append("    1.0 / (inv_sqrt_f * inv_sqrt_f)")
    lines.append("}")
    lines.append("")
    lines.append("fn darcy_pressure_drop_bar(f, length_m, diameter_m, rho, velocity) {")
    lines.append("    let delta_p_pa = f * (length_m / diameter_m) * 0.5 * rho * velocity * velocity;")
    lines.append("    delta_p_pa / 100000.0")
    lines.append("}")
    lines.append("")
    lines.append("fn verify_pressure_drop() {")
    lines.append("    let f = friction_factor_haaland(100000.0, 0.000045, 0.05);")
    lines.append("    if f < 0.015 || f > 0.035 { return false; }")
    lines.append("    true")
    lines.append("}")
    lines.append("if verify_pressure_drop() { log_info(\"[FLUID::PRESSURE_DROP] Verification passed.\"); }")

    for i in range(1, 45):
        lines.append(f"fn line_segment_loss_{i}(flow_rate_kg_s) {{")
        lines.append(f"    let dp = 0.05 * (flow_rate_kg_s + {i} * 0.1).powf(1.85);")
        lines.append(f"    #{{\"segment\": {i}, \"delta_p_bar\": dp}}")
        lines.append(f"}}")

    write_rhai_file(os.path.join(SCRIPTS_DIR, "fluid", "pressure_drop.rhai"), "\n".join(lines))

def gen_cavitating_venturi():
    lines = []
    lines.append("// Cavitating Venturi Mass Flow Regulation and Sonic Choking")
    lines.append("// Acoustic decoupling of propellant feedlines from combustion oscillations")
    lines.append("")
    lines.append("fn venturi_choked_mass_flow(cd, throat_area_sq_m, rho_upstream, p_in_bar, p_vapor_bar) {")
    lines.append("    let delta_p_pa = (p_in_bar - p_vapor_bar) * 100000.0;")
    lines.append("    if delta_p_pa <= 0.0 { return 0.0; }")
    lines.append("    cd * throat_area_sq_m * (2.0 * rho_upstream * delta_p_pa).sqrt()")
    lines.append("}")
    lines.append("")
    lines.append("fn venturi_is_choked(p_recovery_bar, p_in_bar, critical_ratio) {")
    lines.append("    let r = p_recovery_bar / p_in_bar;")
    lines.append("    r <= critical_ratio")
    lines.append("}")
    lines.append("")
    lines.append("fn verify_venturi() {")
    lines.append("    let mdot = venturi_choked_mass_flow(0.96, 0.0005, 1141.0, 40.0, 1.0);")
    lines.append("    if mdot < 10.0 || mdot > 100.0 { return false; }")
    lines.append("    true")
    lines.append("}")
