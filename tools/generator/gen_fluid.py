def gen_pipe_flow():
    lines = []
    lines.append("// Transient Liquid Water Hammer and Cryogenic Surge Pressure")
    lines.append("// Joukowsky acoustic wave propagation in structural piping")
    lines.append("")
    lines.append("fn joukowsky_surge_bar(rho, wave_speed_m_s, delta_v_m_s) {")
    lines.append("    let delta_p_pa = rho * wave_speed_m_s * delta_v_m_s;")
    lines.append("    delta_p_pa / 100000.0")
    lines.append("}")
    lines.append("")
    lines.append("fn pipe_acoustic_wave_speed(bulk_modulus_pa, rho, youngs_mod_pa, diameter_m, thickness_m) {")
    lines.append("    let elasticity_term = (bulk_modulus_pa / youngs_mod_pa) * (diameter_m / thickness_m);")
    lines.append("    let effective_k = bulk_modulus_pa / (1.0 + elasticity_term);")
    lines.append("    (effective_k / rho).sqrt()")
    lines.append("}")
    lines.append("")
    lines.append("fn verify_pipe_flow() {")
    lines.append("    let surge = joukowsky_surge_bar(1141.0, 1000.0, 5.0);")
    lines.append("    // 1141 * 1000 * 5 = 5.705e6 Pa = 57.05 bar")
    lines.append("    if (surge - 57.05).abs() > 0.5 { return false; }")
    lines.append("    true")
    lines.append("}")
    lines.append("if verify_pipe_flow() { log_info(\"[FLUID::PIPE_FLOW] Verification passed.\"); }")

    for i in range(1, 45):
        lines.append(f"fn transient_line_pulse_{i}(delta_v) {{")
        lines.append(f"    let s = joukowsky_surge_bar(1141.0, 1000.0 + {i} * 5.0, delta_v);")
        lines.append(f"    #{{\"station\": {i}, \"surge_bar\": s}}")
        lines.append(f"}}")

    write_rhai_file(os.path.join(SCRIPTS_DIR, "fluid", "pipe_flow.rhai"), "\n".join(lines))

